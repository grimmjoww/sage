#!/usr/bin/env python3
r"""
emit_agents_md.py — compose the MiniMax Code eager core into AGENTS.md.

Reads the shared instructions body on stdin-arg 1 and the merged constitution
on stdin-arg 2, writes the result to stdout. The shell redirects that into
AGENTS.md.

Why a separate program rather than `sed`
----------------------------------------
The merged constitution is prose: markdown tables, code fences, URLs. It
contains `|`, `\` and `/`. A `sed "s|PLACEHOLDER|$CONST|"` collides with the
table pipes and dies with "unterminated `s' command" — and because the
generator runs under `set -e`, that killed the whole run while `sage init`
still reported success. A conformance check that only asks "did generation
succeed" cannot see that no AGENTS.md was written; it is exactly the class of
failure the port's own gates exist to prevent.

Plain string replacement has no delimiter and no escaping problem.

Why the constitution is never dropped
-------------------------------------
constitution.contract.md: the merged constitution is "the only document that
is always present... This is non-negotiable." If the shared body carries no
placeholder, the constitution is APPENDED rather than skipped. Losing it
silently would leave a project that believes it is governed and is not.
"""

from __future__ import annotations

import pathlib
import sys

PLACEHOLDER = "__CONSTITUTION_PLACEHOLDER__"
BEGIN_MARK = "<!-- sage:begin"
END_MARK = "<!-- sage:end -->"


def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write("usage: emit_agents_md.py <body-file> <const-file>\n")
        return 2

    body = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8", errors="replace")
    constitution = pathlib.Path(sys.argv[2]).read_text(encoding="utf-8", errors="replace")

    if PLACEHOLDER in body:
        merged = body.replace(PLACEHOLDER, constitution)
    elif constitution.strip():
        sys.stderr.write(
            "emit_agents_md: no constitution placeholder in the shared body; "
            "appending instead — the constitution is always-on.\n")
        merged = body.rstrip("\n") + "\n\n" + constitution.strip() + "\n"
    else:
        sys.stderr.write(
            "emit_agents_md: WARNING — empty constitution. Writing the body "
            "alone. This is a degraded install, not a clean one.\n")
        merged = body

    if not merged.strip():
        sys.stderr.write("emit_agents_md: composed output is empty; refusing to write\n")
        return 1

    out = f"{BEGIN_MARK} — generated by sage init; edit outside this block -->\n"
    out += merged if merged.endswith("\n") else merged + "\n"
    out += f"{END_MARK}\n"

    sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
